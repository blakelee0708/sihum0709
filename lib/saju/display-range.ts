/**
 * 운 지수 표시 범위 (FIX_4 [1])
 *
 * 계산은 0~100으로 하고 표시만 40~95로 옮깁니다. 20~30점이 그대로 나오면
 * 시험을 앞둔 사람이 낙담합니다. 희망을 주려고 만든 서비스가 반대로
 * 작용합니다.
 *
 * 0~100이 임의의 범위였듯 40~95도 임의입니다. 이 지표는 절대값이 아니라
 * 상대적 차이가 의미를 갖고, 매핑이 선형이라 순위와 차이의 비율은 그대로
 * 유지됩니다.
 *
 *   계산 0 → 40 · 20 → 51 · 50 → 68 · 80 → 84 · 100 → 95
 *
 * fortune.ts가 아니라 이 파일에 둡니다. 차트 컴포넌트가 축을 그리려고
 * 이 상수를 쓰는데, fortune.ts를 import하면 절기표(31KB)까지 클라이언트
 * 번들에 딸려 들어갑니다.
 */

/** 표시 하한 */
export const DISPLAY_MIN = 40
/** 표시 상한 */
export const DISPLAY_MAX = 95

/**
 * 계산값 0~100을 표시값 40~95로 옮깁니다.
 *
 * 이 함수를 통과한 값만 화면·프롬프트·DB에 나갑니다. 계산 중간값에
 * 두 번 적용하지 마십시오.
 */
export function toDisplayScore(raw: number): number {
  return Math.round(DISPLAY_MIN + (raw / 100) * (DISPLAY_MAX - DISPLAY_MIN))
}
